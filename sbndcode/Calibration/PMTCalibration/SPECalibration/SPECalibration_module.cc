  class SPECalibration : public art::EDAnalyzer {
    public:
    explicit SPECalibration(fhicl::ParameterSet const & p);
    // The destructor generated by the compiler is fine for classes
    // without bare pointers or other resource use.

    // Plugins should not be copied or assigned.
    SPECalibration(SPECalibration const &) = delete;
    SPECalibration(SPECalibration &&) = delete;
    SPECalibration & operator = (SPECalibration const &) = delete;
    SPECalibration & operator = (SPECalibration &&) = delete;

    // Required functions.
    void analyze(art::Event const & e) override;

    //Selected optional functions
    void beginJob() override;
    void endJob() override;

    opdet::sbndPDMapAlg pdMap; //map for photon detector types  USE THIS TO SELECT ONLY PMTs!!

    private:

    std::vector<std::string> fOpChannelsType;
    std::vector<int> fOpChannelList;
    int fMaxPulseAmp;
    int fMaxNPeaks; // Max number of peaks to be found in a single waveform

    // Declare member data here.
    std::string fInputModuleName;
    std::stringstream histname;
    std::string opdetType;
    std::string opdetElectronics;
    double fNstdev; //number of noise stdevs to set the threshold to
    int fSpe_region_start; //number of bins after which SPE search starts
    std::vector<TH1D *> amp;
    art::ServiceHandle<art::TFileService> tfs;
  };

  SPECalibration::SPECalibration(fhicl::ParameterSet const & p)
  :
  EDAnalyzer(p) { // ,
    // More initializers here.

    fInputModuleName = p.get< std::string >("InputModule" );
    fNstdev = p.get < double >("nstdev");
    fSpe_region_start = p.get < int >("spe_region_start");
    fOpChannelsType = p.get < std::vector<std::string> >("OpChannelsType");
    fMaxPulseAmp = p.get < double >("MaxPulseAmp");
    fMaxNPeaks = p.get < int >("MaxNPeaks");

    geo::WireReadoutGeom const& fWireReadout = art::ServiceHandle<geo::WireReadout>()->Get();

    for(unsigned int opch=0; opch<fWireReadout.NOpChannels(); opch++){
      std::string _pd_type = pdMap.pdType(opch);
      if(std::find(fOpChannelsType.begin(), fOpChannelsType.end(), _pd_type) == fOpChannelsType.end()) continue; //skip if not in the list of types
      else fOpChannelList.push_back(opch); //if in the list, save the channel number for later use
    }

    for(unsigned int ch=0;ch<fOpChannelList.size();ch++)
    {
      amp.push_back(tfs->make< TH1D >(Form("amp_opchannel_%i", fOpChannelList[ch]), Form("Amplitude of SPEs, channel %i;Amplitude[ADC];Count", fOpChannelList[ch]), 200, 0, 200)); // create histogram for amplitude
    }
  }

