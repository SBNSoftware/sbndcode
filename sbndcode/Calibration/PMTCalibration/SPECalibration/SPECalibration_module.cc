  void SPECalibration::analyze(art::Event const & e)
  {

    art::Handle<std::vector<raw::OpDetWaveform>> waveHandle;
    e.getByLabel(fInputModuleName, waveHandle);

    if(!waveHandle.isValid()) {
      std::cout << Form(
        "Did not find any G4 photons from producer %s",
        "largeant"
      ) << std::endl;

      return;
    }

    double pulse_peak;
    double pulse_t_start;
    double pulse_t_end;
    double pulse_t_peak;

    std::vector<double> pulse_t_peak_v;

    int total_nspe = 0;

    int success = 0;
    int failed = 0;

    std::cout
        << "Number of waveforms: "
        << waveHandle->size()
        << std::endl;

    for(auto const& wvf : (*waveHandle))
    {
      int wvf_ch = wvf.ChannelNumber();

      opdetType        = pdMap.pdType(wvf_ch);
      opdetElectronics = pdMap.electronicsType(wvf_ch);
      
      //--------------------------------------------------
      // BASELINE ESTIMATION
      //--------------------------------------------------

      const int wvf_nbins = wvf.size();
      std::vector<int> sortedWVF( wvf.begin(), wvf.end());
      std::sort( sortedWVF.begin(), sortedWVF.end());

      double baseline;
      int n = sortedWVF.size();
      if(n % 2 == 0){
        baseline = 0.5 * ( sortedWVF[n/2 - 1] + sortedWVF[n/2] );
      }
      else{
        baseline = sortedWVF[n/2];
      }

      //--------------------------------------------------
      // BASELINE SUBTRACTION + POLARITY FLIP
      //--------------------------------------------------

      std::vector<double> wvfm(wvf_nbins, 0);

      for(int i=0;i<wvf_nbins;i++){
        wvfm[i] = baseline - (double)wvf[i];
      }

      //--------------------------------------------------
      // REJECT LARGE PULSES
      //--------------------------------------------------

      double max_value = *std::max_element( wvfm.begin(), wvfm.end());

      if(max_value > fMaxPulseAmp)
        continue;

      //--------------------------------------------------
      // NOISE ESTIMATION USING FULL WAVEFORM
      //--------------------------------------------------

      double totalvar = 0;

      for(int i=0;i<wvf_nbins;i++){
        double val = wvfm[i];
        totalvar +=val*val;
      }

      double stdev = sqrt(totalvar / wvf_nbins);
      double thresh = stdev * fNstdev;

      //--------------------------------------------------
      // PEAK FINDER
      //--------------------------------------------------

      bool fire = false;

      int counter = fSpe_region_start;

      int peak_count = 0;

      pulse_t_peak_v.clear();

      pulse_peak    = 0;
      pulse_t_start = 0;
      pulse_t_end   = 0;
      pulse_t_peak  = 0;

      for(unsigned int i=fSpe_region_start;i<wvfm.size();i++)
      {
        double adc =
            wvfm[counter];

        if(!fire && adc > thresh){
          fire = true;
          pulse_t_start = counter-1 > 0?counter-1:counter;
        }

        else if(fire && adc < thresh){
          fire = false;
          pulse_t_end = counter <(int)wvfm.size()?counter:counter-1;

          if(pulse_t_end-pulse_t_start>2){
            pulse_t_peak_v.push_back(pulse_t_peak);
            peak_count++;
          }

          pulse_peak    = 0;
          pulse_t_start = 0;
          pulse_t_end   = 0;
          pulse_t_peak  = 0;
        }

        else if(fire){
          if(adc > pulse_peak){
            pulse_peak = adc;
            pulse_t_peak = counter;
          }
        }
        counter++;

        if(peak_count == fMaxNPeaks){
          failed++;
          continue;
        }
      }

      //--------------------------------------------------
      // HANDLE OPEN PULSE
      //--------------------------------------------------

      if(fire){
        fire = false;
        pulse_t_end = counter-1;
      }

      //--------------------------------------------------
      // AMPLITUDES
      //--------------------------------------------------

      int nspe = pulse_t_peak_v.size();

      if(nspe == 0){
        failed++;
        continue;
      }

      for(int i=0; i<nspe; i++){
        int peakbin = pulse_t_peak_v[i];
        double ampsum = 0;
        int ampnumBins = 0;
        for(int j=peakbin-20; j<=peakbin+20; j++)
        {
          if(j>=0 && j<(int)wvfm.size())
          {
            ampsum += wvfm[j];
            ampnumBins++;
          }
        }

        double localBaseline = ampsum / ampnumBins;
        double peakheight = wvfm[peakbin]-localBaseline;

        int idx = std::find(fOpChannelList.begin(), fOpChannelList.end(), wvf_ch) - fOpChannelList.begin();
        amp[idx]->Fill(
            peakheight
        );
      }

      success++;
      total_nspe +=peak_count;
    }

    //--------------------------------------------------
    // FINAL PRINT
    //--------------------------------------------------

    std::cout
        << "Analysis complete\n"
        << "Successful waveforms: "
        << success
        << "\nFailed waveforms: "
        << failed
        << "\nTotal SPEs: "
        << total_nspe
        << std::endl;
  }

  void SPECalibration::endJob()
  {

  }

